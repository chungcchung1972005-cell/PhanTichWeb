const assert = require('assert/strict');
const crypto = require('crypto');
process.env.AUTH_SECRET = 'photo-rounds-local-test';
process.env.MONGODB_URI = '';
process.env.EDIT_REQUESTS_MONGODB_URI = '';
const express = require('../server/node_modules/express');
const { memoryStore } = require('../server/edit-requests-store');
const { createEditRequestsRouter } = require('../server/edit-requests');
const {createService}=require('../server/workflow');
(async () => {
  const store = memoryStore();
  const workflow=createService(memoryStore());
  const boss={role:'sep',phone:'0911111111'},worker={role:'tho-anh',phone:'0912345679'},sale={role:'sale',phone:'0912345677'};
  await workflow.change(boss,'employee',{phone:worker.phone,name:'Test photographer',role:'tho-anh'});
  await workflow.change(sale,'book',{id:'workflow-test',code:'#ROUNDTEST',phone:'0912345678',customerName:'Test customer',service:'Newborn',pkg:'Cơ bản',price:1500000,date:'2026-11-01',time:'09:00',shooterPhone:worker.phone,editorPhone:worker.phone});
  await workflow.change(sale,'payment',{id:'workflow-test',amount:750000,reference:'test-deposit'});
  await workflow.change(worker,'checkin',{id:'workflow-test'});await workflow.change(worker,'shot',{id:'workflow-test'});
  const app = express(); app.use(express.json()); app.use('/edit', createEditRequestsRouter(store,{workflowService:workflow}));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const body = Buffer.from(JSON.stringify({role:'khach-hang', phone:'0912345678', name:'Test', exp:Date.now()+60000})).toString('base64url');
  const token = body + '.' + crypto.createHmac('sha256', process.env.AUTH_SECRET).update(body).digest('base64url');
  let sourceAlbumId;
  const photos = n => Array.from({length:n}, (_,i) => ({id:'drive-test-file-000'+i, driveFileId:'test-file-000'+i, name:'IMG_'+i+'.JPG', src:'images/my-photos/photo-1.jpg', isExtra:false}));
  const create = async data => {
    const r = await fetch(`http://127.0.0.1:${server.address().port}/edit`, {method:'POST', headers:{'content-type':'application/json', authorization:'Bearer '+token}, body:JSON.stringify(Object.assign({sourceAlbumId}, data))});
    return {status:r.status, data:await r.json()};
  };
  try {
    const base = `http://127.0.0.1:${server.address().port}/edit`;
    const staffBody = Buffer.from(JSON.stringify({role:'tho-anh', phone:'0912345679', name:'Test photographer', exp:Date.now()+60000})).toString('base64url');
    const staffToken = staffBody + '.' + crypto.createHmac('sha256', process.env.AUTH_SECRET).update(staffBody).digest('base64url');
    const albumPayload = {workflowOrderId:'workflow-test',folderUrl:'https://drive.google.com/drive/folders/test-folder-12345', photos:photos(12)};
    let delivery = await fetch(base+'/albums', {method:'POST', headers:{'content-type':'application/json', authorization:'Bearer '+token}, body:JSON.stringify(albumPayload)});
    assert.equal(delivery.status,403);
    delivery = await fetch(base+'/albums', {method:'POST', headers:{'content-type':'application/json', authorization:'Bearer '+staffToken}, body:JSON.stringify(albumPayload)});
    assert.equal(delivery.status,201);
    const delivered = (await delivery.json()).album;
    sourceAlbumId = delivered.id;
    const mine = await (await fetch(base+'/albums/me', {headers:{authorization:'Bearer '+token}})).json();
    assert.equal(mine.albums.length,1);
    const otherBody = Buffer.from(JSON.stringify({role:'khach-hang', phone:'0912345680', name:'Other customer', exp:Date.now()+60000})).toString('base64url');
    const otherToken = otherBody + '.' + crypto.createHmac('sha256', process.env.AUTH_SECRET).update(otherBody).digest('base64url');
    const otherAlbums = await (await fetch(base+'/albums/me', {headers:{authorization:'Bearer '+otherToken}})).json(); assert.deepEqual(otherAlbums.albums,[]);
    const foreign = await fetch(base, {method:'POST', headers:{'content-type':'application/json',authorization:'Bearer '+otherToken},body:JSON.stringify({sourceAlbumId,orderCode:'#ROUNDTEST',photos:photos(1),extraFee:0})}); assert.equal(foreign.status,400);
    const requestList = await (await fetch(base+'/me', {headers:{authorization:'Bearer '+token}})).json(); assert.equal(requestList.requests.length,0);
    let invalid = await create({orderCode:'#ROUNDTEST', photos:[{id:'drive-foreign-file-000',src:'images/my-photos/photo-1.jpg'}], extraFee:0}); assert.equal(invalid.status,400);
    invalid = await create({orderCode:'#ROUNDTEST', sourceAlbumId:'AL-not-mine', photos:photos(1), extraFee:0}); assert.equal(invalid.status,400);
    let r = await create({orderCode:'#ROUNDTEST', photos:photos(11), extraFee:0}); assert.equal(r.status,400);
    r = await create({orderCode:'#ROUNDTEST', photos:photos(11), extraFee:50000}); assert.equal(r.status,201);
    assert.equal(r.data.request.extraCount,1); assert.equal(r.data.request.round,1);
    assert.equal(r.data.request.photos[0].name,'IMG_0.JPG');
    assert.match(r.data.request.photos[0].driveUrl,/test-file-0000/);
    const first = r.data.request;
    r = await create({orderCode:'#ROUNDTEST', parentRequestId:first.id, photos:photos(1), extraFee:50000}); assert.equal(r.status,409);
    await store.updateIfRev(first.id, first.rev, {status:'Hoàn thành', resultLink:'https://drive.google.com/drive/folders/test-folder-123'});
    r = await create({orderCode:'#ROUNDTEST', parentRequestId:first.id, photos:photos(2), extraFee:0}); assert.equal(r.status,400);
    r = await create({orderCode:'#ROUNDTEST', parentRequestId:first.id, photos:photos(2), extraFee:100000}); assert.equal(r.status,201);
    assert.equal(r.data.request.round,2); assert.equal(r.data.request.extraCount,2);
    assert.equal(r.data.request.parentRequestId,first.id);
    const second = r.data.request;
    await store.updateIfRev(second.id, second.rev, {status:'Hoàn thành', resultLink:'https://drive.google.com/drive/folders/test-folder-456'});
    r = await create({orderCode:'#ROUNDTEST', parentRequestId:second.id, photos:photos(1), extraFee:50000}); assert.equal(r.status,201);
    assert.equal(r.data.request.round,3); assert.equal(r.data.request.extraFee,50000);
    r = await create({orderCode:'#OTHERORDER', parentRequestId:first.id, photos:photos(1), extraFee:50000}); assert.equal(r.status,400);
    console.log('PASS: staff delivery before selection, customer permissions, album membership, filenames and original Drive links, authoritative pricing through 3 rounds, order isolation');
  } finally { await new Promise(resolve => server.close(resolve)); }
})().catch(e => { console.error(e); process.exitCode=1; });
